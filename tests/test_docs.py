"""Documentation tests: the numbers we show judges must be what the code produces.

If someone changes the code (or the README) so they disagree, these fail."""

import os
import re

import pytest

import evaluate as ev
from q_learning import train, run_agent
from gym_env import CPUSchedulingEnv
from simulator import CPUSimulator
from workload_generator import load_workload_csv, REPORT_SAMPLE_WORKLOAD

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
README_NAMES = {
    "FCFS": "FCFS",
    "Round Robin (q = 3)": "Round Robin",
    "Priority": "Priority",
    "RL (Q-learning)": ev.RL_NAME,
    "SJF (reference, needs burst times in advance)": "SJF (reference)",
}


def _read(name):
    with open(os.path.join(ROOT, name), encoding="utf-8") as f:
        return f.read()


@pytest.fixture(scope="module")
def default_agent():
    """Exactly the agent `python main.py` trains (default settings, seed 0)."""
    agent, _ = train(verbose_every=0)
    return agent


@pytest.fixture(scope="module")
def standard_summary(default_agent):
    scenarios = {"standard": ev.SCENARIOS["standard"]}
    df = ev.evaluate({ev.RL_NAME: default_agent}, scenarios=scenarios, num_workloads=100)
    return ev.summarize(df).set_index("scheduler"), ev.significance(df)


def test_readme_headline_table_matches_the_code(standard_summary):
    summary, _ = standard_summary
    rows = re.findall(r"^\| \**(.+?)\** \| \**([\d.]+)\** \| \**([\d.]+)\** \| \**([\d.]+)\** "
                      r"\| \**([\d.]+)\** \|$", _read("README.md"), flags=re.M)
    assert len(rows) == 5, "README headline table not found"
    for name, wait, tat, max_wait, fairness in rows:
        s = summary.loc[README_NAMES[name]]
        assert float(wait) == pytest.approx(s.avg_waiting_time_mean, abs=0.006), name
        assert float(tat) == pytest.approx(s.avg_turnaround_time_mean, abs=0.006), name
        assert float(max_wait) == pytest.approx(s.max_waiting_time_mean, abs=0.006), name
        assert float(fairness) == pytest.approx(s.fairness_index_mean, abs=0.006), name


def test_readme_improvement_claims_match_the_code(standard_summary):
    _, sig = standard_summary
    claim = re.search(r"by \*\*(\d+) % vs FCFS, (\d+) % vs Round Robin and (\d+) % vs Priority",
                      _read("README.md"))
    assert claim, "improvement sentence not found in README"
    for baseline, pct in zip(["FCFS", "Round Robin", "Priority"], claim.groups()):
        row = sig[(sig.baseline == baseline) & (sig.metric == "avg_waiting_time")].iloc[0]
        assert round(row.improvement_pct) == int(pct), baseline
        assert row.significant_better, baseline


@pytest.mark.parametrize("csv_name, expected_rl, expected_fcfs", [
    ("report_appendix_a.csv", 5.6, 8.2),
    ("convoy_effect.csv", 3.2, 18.2),
])
def test_example_workload_numbers_in_docs(default_agent, csv_name, expected_rl, expected_fcfs):
    from fcfs import run_fcfs
    w = load_workload_csv(os.path.join(ROOT, "examples", csv_name))
    env = CPUSchedulingEnv(workload=w, max_queue_size=default_agent.num_actions)
    assert run_agent(default_agent, env)["avg_waiting_time"] == pytest.approx(expected_rl)
    assert run_fcfs(CPUSimulator(w))["avg_waiting_time"] == pytest.approx(expected_fcfs)
    for doc in ("examples/README.md", "PRESENTATION.md"):
        assert f"{expected_fcfs}" in _read(doc)


def test_every_file_mentioned_in_readme_exists():
    readme = _read("README.md")
    for path in set(re.findall(r"`((?:examples|results|tests)/[\w./-]+|[\w-]+\.(?:py|md|bat))`",
                               readme)):
        if path.startswith("results/"):
            continue   # generated by `python main.py`
        assert os.path.exists(os.path.join(ROOT, path)), path


def test_report_sample_workload_is_the_appendix_a_table():
    # Report Appendix A: P1(0,5,2) P2(1,3,1) P3(2,8,4) P4(3,6,3) P5(4,2,5)
    assert [(p.id, p.arrival_time, p.burst_time, p.priority) for p in REPORT_SAMPLE_WORKLOAD] == [
        ("P1", 0, 5, 2), ("P2", 1, 3, 1), ("P3", 2, 8, 4), ("P4", 3, 6, 3), ("P5", 4, 2, 5)]
